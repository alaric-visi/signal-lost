/* char -> flat list of (x, y) pixel coordinates */
export const GLYPHS = new Map<string, number[]>();
for (const ch in G) {
  const px: number[] = [];
  G[ch].split(' ').forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === '#') px.push(x, y);
  });
  GLYPHS.set(ch, px);
}
